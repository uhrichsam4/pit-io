/**
 * MIAMI DEVOUR — NPC VOICE PLAYBACK / REACTION FRAMEWORK  (spec section 4)
 *
 * This module decides WHO speaks, WHEN, and HOW LOUD. It does not synthesise
 * anything and it does not know what a hole is: the game calls `say()` with a
 * category ('notice', 'flee', 'police_warning', …) and a world position, and
 * everything else — cooldowns, concurrency, distance culling, subtitles,
 * ducking — happens in here.
 *
 * ---------------------------------------------------------------------------
 * THE DEFAULT STATE IS "NO AUDIO ASSETS"
 *
 * The ElevenLabs key lives server-side and the voice bank is generated by an
 * offline batch job (spec section 4, "generation workflow"). Until the owner
 * supplies a key there is no manifest and no .webm on disk — so CAPTIONS ONLY
 * is the *normal* path, not the error path. `load()` never throws, never
 * rejects, and a failed load leaves a fully functional, fully rate-limited
 * caption system behind. Everything below (cooldowns, concurrency, the burst
 * damper, distance culling) runs identically in both modes, which means the
 * chatter *rhythm* the designer tunes with captions is the rhythm players get
 * once the audio lands. That is the whole reason the limiter is not bolted to
 * the playback code.
 *
 * ---------------------------------------------------------------------------
 * SIGNAL FLOW  (audio mode only)
 *
 *   AudioBufferSource ─▶ per-line gain ─▶ StereoPanner ─▶ deps.destination
 *                                                          (the mixer's voice
 *                                                           bus — we never
 *                                                           touch audio.js)
 *
 * Ducking is *published*, not applied: `voice.duckAmount` is a 0..1 number the
 * mixer reads each frame and multiplies into its own ambience bus. Reaching
 * into audio.js's internal nodes from here would mean two owners for one
 * GainParam, and the loser of that race is always the ambience bed.
 *
 * ---------------------------------------------------------------------------
 * RATE LIMITING — the actual difficulty (spec: "Do not make every NPC scream
 * at once. Use cooldowns, distance checks, voice concurrency limits, and
 * weighted variation.")
 *
 * Six independent gates, cheapest first, because in a crowd scene `say()` is
 * called dozens of times per second and 95% of those calls must die before
 * they allocate anything:
 *
 *   1. DISTANCE      — an NPC outside the audible ring returns immediately.
 *                      No line selection, no allocation, no caption. This is
 *                      first because it is one hypot and it rejects most of a
 *                      panicking crowd.
 *   2. GLOBAL GAP    — MIN_START_GAP between any two line starts, so three
 *                      NPCs that trigger in the same frame become a staggered
 *                      exchange instead of a chord.
 *   3. CONCURRENCY   — hard cap of 3 (spec says 2–3). Never exceeded, not by
 *                      `force`, not by a CRITICAL police line: a high priority
 *                      line *evicts* a lower one rather than adding a fourth.
 *   4. BURST DAMPER  — token bucket, see BURST_* below.
 *   5. COOLDOWNS     — per voice (a cast may not chatter), per speaker (one
 *                      NPC may not chatter), per category (no wave of 'notice').
 *   6. PER-LINE      — folded into the weighted pick: a line used inside
 *                      LINE_COOLDOWN gets weight 0, and the last few lines used
 *                      get a heavy weight penalty, so the same joke does not
 *                      come back twice in a minute.
 *
 * ---------------------------------------------------------------------------
 * DEPENDENCIES
 *
 * Only `./voicelines.js` (the data file, imported as a namespace so a rename of
 * one of its exports cannot break the build) and nothing else. No three, no
 * config.js, no audio.js, no UI. The few world constants needed for panning are
 * mirrored from CAMERA in src/core/quality.js and are overridable via
 * `deps.camera` — see CAMERA_MIRROR for why they are copied rather than
 * imported.
 */

// Namespace import on purpose. A named import of a symbol the data file does
// not export is a hard build failure, and this module is written before that
// file is finished; `_adaptLibrary` probes the shape at runtime instead and
// falls back to a tiny built-in bank if it recognises nothing. Guessing an
// export name here is exactly the failure mode the house rules warn about.
import * as LINE_LIB from './voicelines.js';

/* ======================================================== tuning ======= */

/** Priority ladder. Higher wins evictions and unlocks the long-range paths. */
export const VOICE_PRIORITY = {
  /** Idle flavour. First thing dropped, never heard off-screen. */
  CHATTER: 0,
  /** A reaction to the player: notice, flee, near miss, prop eaten. */
  REACT: 1,
  /** Police warnings, event announcements. Audible anywhere, ducks ambience. */
  IMPORTANT: 2,
  /** Match-defining callouts. May evict anything below it. */
  CRITICAL: 3,
};

/**
 * Every number the balance pass will want to touch. Exported so the tuner and
 * the tests read the same values — a magic number duplicated in a test is a
 * test that passes after the tuning changes and proves nothing.
 */
export const VOICE_TUNING = {
  /** Spec: "no more than 2-3 spoken lines at once". 3, and it is a hard cap. */
  MAX_CONCURRENT: 3,

  /**
   * Minimum seconds between two line STARTS. 0.42 s ≈ the gap a human leaves
   * before answering: below ~0.3 s two lines read as one garbled event, above
   * ~0.6 s a crowd stops feeling like a crowd.
   */
  MIN_START_GAP: 0.42,

  /* --- cooldowns ----------------------------------------------------- */
  /** Per cast (voice profile). Longer than the longest line by ~2×. */
  VOICE_COOLDOWN: 5.0,
  /** Per individual NPC. One pedestrian gets one line per approach, roughly. */
  SPEAKER_COOLDOWN: 7.0,
  /** Per category — stops forty simultaneous 'flee's becoming a queue. */
  CATEGORY_COOLDOWN: 1.6,
  /** Per line id. A player hears ~25 lines a match; 14 s ≈ no near-repeats. */
  LINE_COOLDOWN: 14.0,

  /* --- burst damper ---------------------------------------------------- */
  /**
   * Token bucket. WHY a bucket and not just a cooldown: the moment the hole
   * turns a corner, forty pedestrians pass the distance check in the same
   * frame. A plain cooldown produces a metronome — one line, exactly every N
   * seconds, forever, which sounds like a machine. A bucket gives the honest
   * shape of a real crowd: a short flurry as everyone notices (4 lines inside
   * ~2 s), then a thinning-out to a sustained mutter.
   *
   * CAPACITY 4 = the flurry size. REFILL 0.55/s = one line per ~1.8 s
   * sustained, which is a little slower than the 3-slot concurrency cap can
   * drain, so the cap stops being the binding constraint after the flurry —
   * exactly the intent.
   */
  BURST_CAPACITY: 4,
  BURST_REFILL: 0.55,

  /* --- distance -------------------------------------------------------- */
  /**
   * Audible / caption ranges as multiples of the camera's ground half-width,
   * so they scale with the hole the way the framing does: a 40 m hole sees a
   * much wider slice of city, and its NPCs must be audible across it.
   * 2.0 ≈ a bit beyond the screen edge (a voice may precede its owner).
   * 1.25 ≈ on-screen only — captions for someone you cannot see are noise.
   */
  AUDIBLE_MULT: 2.0,
  CAPTION_MULT: 1.25,
  /** Floor for tiny holes, so a match still starts with audible neighbours. */
  MIN_AUDIBLE: 34,

  /* --- mixing ---------------------------------------------------------- */
  /** Ambience dip while an IMPORTANT+ line plays. Slight, per spec. */
  DUCK_AMOUNT: 0.18,
  /** Fast in so the first syllable is already clear, slow out so it breathes. */
  DUCK_ATTACK: 0.09,
  DUCK_RELEASE: 0.45,
  /** Attenuation floor for IMPORTANT+ lines: a dispatcher is never inaudible. */
  IMPORTANT_GAIN_FLOOR: 0.55,
  /** Panning is narrowed for important lines — clarity beats localisation. */
  IMPORTANT_SPREAD: 0.45,

  /* --- captions -------------------------------------------------------- */
  /**
   * Caption + slot-reservation duration estimate when the real length is unknown
   * (captions-only mode, or before the buffer has decoded). 0.34 s per word is
   * ~175 wpm — a touch slower than the excited delivery these lines get, which
   * biases the estimate long. Long is the safe direction: it under-fills the
   * concurrency cap rather than over-filling it.
   */
  CAPTION_PER_WORD: 0.34,
  CAPTION_MIN: 1.1,
  CAPTION_MAX: 5.0,

  /* --- variation -------------------------------------------------------- */
  /** How many recently spoken line ids are remembered per category. */
  RECENT_MEMORY: 6,
  /** Weight multiplier applied to a remembered line. Not 0: never say never. */
  RECENT_PENALTY: 0.12,

  /** Decoded buffers kept in memory. ~40 short lines ≈ a couple of MB. */
  BUFFER_CACHE: 96,

  /**
   * A handle whose source never reported `ended` is force-retired this many
   * seconds past its expected end. Without it, one missed `onended` (they do
   * get dropped when a context is suspended by a tab switch mid-line) leaks a
   * concurrency slot, and three leaks make the city silent for the rest of the
   * match with no error anywhere.
   */
  ZOMBIE_GRACE: 2.0,
};

